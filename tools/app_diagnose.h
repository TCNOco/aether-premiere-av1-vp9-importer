// Сбор диагностики: что за машина, что из Adobe стоит, жив ли плагин и
// распаковывается ли видео.
//
// Отделено от окна намеренно. Во-первых, это единственная часть, которую можно
// проверить без человека у экрана. Во-вторых, прогон занимает секунды и обязан
// идти в отдельном потоке — окно, которое замерло на «проверяем», выглядит
// сломанным, а не занятым.
//
// Что эта проверка НЕ доказывает: что Premiere сумеет открыть файл. Мы
// проверяем своё ядро на этой машине. Premiere ходит к плагину своим путём,
// со своими наборами функций, и подменить его нельзя ничем, кроме самого
// Premiere. В отчёте это сказано прямым текстом, чтобы «всё PASS» никого
// не вводило в заблуждение.
#pragma once

#include <functional>
#include <string>
#include <vector>

namespace aether {

enum class State {
    Pass,     // проверено и работает
    Fail,     // проверено и не работает
    Warn,     // работает, но что-то не так
    Info,     // не проверка, а сведения: версия, имя, число
    Skip,     // проверять было нечем
};

struct Check {
    std::wstring name;
    State        state = State::Info;
    std::wstring detail;
};

struct Section {
    std::wstring       title;
    std::vector<Check> checks;
};

struct Report {
    std::vector<Section> sections;

    // Есть ли хоть один провал — по нему окно решает, каким показать итог
    bool AnyFailed() const;

    // То же самое в JSON — для панели внутри Premiere.
    //
    // Панель написана на HTML и распаковывать видео не умеет ни в каком виде,
    // поэтому зовёт этот же движок отдельной программой и читает ответ. Так
    // проверка у панели и у окна буквально одна и та же: расходиться нечему.
    //
    // Чистка здесь тоже применяется: отчёт из панели уезжает туда же, куда
    // и из окна, — в чужой issue.
    std::wstring Json() const;

    // Текст для буфера обмена, УЖЕ вычищенный.
    //
    // Отчёт уезжает в публичный issue, а в путях стоит имя пользователя, да и
    // название рабочего файла выдаёт больше, чем человек собирался показать.
    // Чистка тут не вежливость: без неё мы своими руками научим людей
    // публиковать лишнее.
    std::wstring PlainText() const;
};

// Прогон. Зовётся из рабочего потока; onStep получает название текущего шага,
// чтобы окну было что показывать, пока идёт проверка.
//
// userFile — файл, на который жалуется человек. Пустая строка — пропустить.
Report Run(const std::wstring& userFile,
           const std::function<void(const std::wstring&)>& onStep);

// Убрать из строки имя пользователя и прочее, чему не место в публичном месте.
// Вынесено наружу, потому что окно показывает те же пути на экране.
std::wstring Scrub(const std::wstring& text);

} // namespace aether
