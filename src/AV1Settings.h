// Настройки плагина.
//
// У импортёра нет своего окна настроек (imSetup мы не поддерживаем), поэтому
// единственный способ на него повлиять — файл рядом с ним и переменная среды.
// Это не бедность интерфейса, а осознанный выбор: настройки нужны для обхода
// поломок в чужих драйверах, и включать их должно быть возможно, когда Premiere
// уже не запускается нормально.

#pragma once

namespace av1imp {

// Папка, из которой загружен плагин, с завершающим слэшем.
// Рядом с ним лежат библиотеки ffmpeg и файл настроек.
const wchar_t* PluginDirectory();

// Разрешено ли декодирование на видеокарте.
//
// Выключается, если рядом с плагином лежит AV1Importer.ini со строкой
//   hardware=0
// либо задана переменная среды AV1IMPORTER_HARDWARE=0 (она главнее файла).
//
// Зачем: аппаратные декодеры живут в драйверах видеокарт, а те ломаются —
// от артефактов на отдельных файлах до падения всего Premiere. Программный
// декодер медленнее, но переживает то, на чём спотыкается драйвер, и человеку
// нужен способ переключиться, не дожидаясь новой версии плагина.
//
// Читается один раз при первом обращении.
bool HardwareDecodingEnabled();

} // namespace av1imp
