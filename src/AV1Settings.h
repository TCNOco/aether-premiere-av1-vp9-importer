// Настройки плагина, общие для всех файлов.
//
// Живут в %LOCALAPPDATA%\AV1Importer\settings.ini, а не рядом с плагином:
// папка плагина лежит в Program Files и требует администратора на каждую
// запись. Переключать декодер человек должен без этого.
//
// Своего окна внутри Premiere у импортёра нет намеренно. SDK предлагает два
// пути, и оба хуже: окно по imGetPrefs8 всплывает при импорте каждого файла
// либо перехватывает двойной щелчок по клипу, а панель настроек как у RED
// требует отдельного плагина-эффекта и привязана к клипу, а не к плагину.
// К тому же настройка нужна ровно тогда, когда Premiere из-за драйвера
// не запускается — внутри него она была бы недоступна.
// Переключается программой AV1ImporterSettings.exe (ярлык в меню «Пуск»).

#pragma once

namespace av1imp {

enum class DecodeMode {
    Auto = 0,     // выбрать по числу ядер, см. PreferHardware()
    Software,     // всегда процессор
    Hardware,     // всегда видеокарта
};

// Папка, из которой загружен плагин, с завершающим слэшем.
// Рядом лежат библиотеки ffmpeg. Доступно только внутри плагина.
const wchar_t* PluginDirectory();

// Отложенная подготовка: журнал и библиотеки ffmpeg. Вызывается из точки входа
// плагина, а не при загрузке DLL, — см. длинный комментарий в AV1Runtime.cpp.
// Звать можно сколько угодно раз, работа делается один.
void EnsureRuntime();

// Полный путь к файлу настроек. Папка создаётся при сохранении.
const wchar_t* SettingsFilePath();

// Что выбрано сейчас. Переменная среды AV1IMPORTER_HARDWARE (0/1) главнее файла:
// ею удобно проверить догадку, ничего не сохраняя.
DecodeMode CurrentMode();

// Записать выбор. Возвращает false, если файл не удалось создать.
bool SaveMode(DecodeMode mode);

// Итоговый ответ для декодера: разворачивает Auto в да/нет.
//
// Auto опирается на замер, а не на здравый смысл: аппаратное декодирование
// оказалось МЕДЛЕННЕЕ программного (1440p: 130 против 800 кадров/с), потому что
// Premiere нужны кадры в обычной памяти и за видеокарту приходится платить
// копированием из неё. Но dav1d раскладывается по ядрам, и на слабом процессоре
// расклад развернётся — поэтому на многоядерных выбираем процессор, на слабых
// видеокарту. Порог грубый: проверить его на разном железе было не на чем.
bool PreferHardware();

// Отдавать ли кадры асинхронно. Путь новый и с отдельным потоком внутри чужого
// процесса, поэтому у него есть выключатель: строка `async = off` в том же
// файле настроек или переменная среды AETHER_ASYNC=0.
bool AsyncDeliveryEnabled();

// Отдавать ли кадры в родном YUV, без перевода в RGB. Хост может и не взять —
// тогда всё идёт прежним путём само собой. Выключатель на случай, если возьмёт,
// а цвет уедет: строка `yuv = off` в файле настроек или AETHER_YUV=0.
bool YuvEnabled();

} // namespace av1imp
