// Слой декодирования AV1 поверх ffmpeg.
//
// Намеренно ничего не знает про Adobe SDK: его можно собрать и проверить обычной
// консольной программой (см. tools/decoder_test.cpp), а уже потом подключить к плагину.
// Так отлаживается 90% логики без запуска Premiere.

#pragma once

#include <cstdint>
#include <string>
#include <atomic>
#include <mutex>
#include <vector>
#include <map>

struct AVFormatContext;
struct AVCodecContext;
struct AVFrame;
struct AVPacket;
struct SwsContext;
struct AVBufferRef;
struct SwrContext;

namespace av1imp {

// Что удалось узнать о файле после открытия
// В каком виде отдавать кадр наружу.
//
// Adobe для 16-битных форматов держит белое не на 65535, а на **32768** — так же,
// как After Effects и Photoshop (SDK, стр. 64). Поэтому BGRA16 это не просто
// «то же самое, но шире»: диапазон другой, и перепутать его значит получить
// вдвое пересвеченную картинку.
enum class FrameFormat {
    BGRA8,    // 4 байта на пиксель, 0..255
    BGRA16,   // 8 байт на пиксель, 0..32768
};

struct MediaInfo {
    int      width          = 0;
    int      height         = 0;
    double   fps            = 0.0;   // кадров в секунду
    int      fpsNum         = 0;     // та же частота точной дробью: fpsNum/fpsDen.
    int      fpsDen         = 0;     // Premiere считает время в них, и 60000/1001 округлять нельзя
    int64_t  frameCount     = 0;     // может быть оценкой, если в контейнере нет точного числа
    double   durationSec    = 0.0;
    int      bitDepth       = 8;     // бит на канал в самом файле: 8 или 10

    // Цветовое описание файла кодами ITU — теми же, какими его записывают
    // в поток, и теми же, какими его понимает Premiere.
    //
    // Нужно не только для HDR. Мы отдаём RGB, ничего не преобразуя, кроме
    // матрицы: кривая переноса и первичные цвета остаются исходными. Если про
    // это промолчать, хост подставит своё рабочее пространство — и материал
    // BT.2020 PQ приедет вылинявшим, а лог-кривые плоскими.
    int      colourPrimaries = 1;    // AVCOL_PRI_*  (1 = BT.709, 9 = BT.2020)
    int      colourTransfer  = 1;    // AVCOL_TRC_*  (16 = PQ, 18 = HLG)
    int      colourMatrix    = 1;    // AVCOL_SPC_*  — до пересчёта в RGB
    bool     fullRange       = false;// размах в самом файле

    // Где стоит цветность относительно яркости: AVCHROMA_LOC_*. Нужно только
    // при выдаче без пересчёта — тогда цветность едет к хосту как есть, и он
    // должен знать, как её читать. Ошибка здесь сдвигает цвет на полпикселя:
    // на градиенте незаметно, на резкой границе видно каймой.
    int      chromaLocation  = 0;    // 1 = слева (MPEG-2), 2 = по центру (MPEG-4)
    bool     hasAlpha       = false; // в файле есть прозрачность
    bool     hasVideo       = true;  // false — файл только со звуком
    bool     hardwareDecode = false; // декодирует видеокарта, а не процессор
    std::string codecName;
    std::string decoderName;

    // Звук. Дорожек в файле может быть несколько: запись нередко несёт
    // несколько звуковых потоков сразу, и сводить их в одну нельзя.
    int      audioStreamCount = 0;
    int      audioChannels    = 0;
    int      audioSampleRate  = 0;
    int64_t  audioSampleCount = 0;   // длина в кадрах отсчётов (не в байтах)
};

class Decoder {
public:
    Decoder() = default;
    ~Decoder();

    Decoder(const Decoder&) = delete;
    Decoder& operator=(const Decoder&) = delete;

    // Открыть файл. Путь — UTF-8. Возвращает false, если файл не открылся
    // или кодек не из списка поддерживаемых (импортёр не должен перехватывать
    // форматы, которые Premiere открывает сам).
    //
    // needVideo=false открывает только разбор контейнера, без декодера кадров.
    // Так работают экземпляры, обслуживающие дорожки звука: файл проверяется
    // на AV1 по-прежнему, но лишний декодер на видеокарте не создаётся —
    // иначе на четырёхдорожечной записи их было бы четыре вместо одного.
    bool Open(const std::string& utf8Path, bool preferHardware = true,
              bool needVideo = true);

    // Закрыть всё. Можно звать из любого потока: Premiere закрывает файл
    // не дожидаясь, пока другие его потоки договорят с декодером.
    void Close();

    bool IsOpen() const { return fmt_ != nullptr; }
    const MediaInfo& Info() const { return info_; }

    // Выдать кадр по индексу в буфер вызывающего.
    // Формат — BGRA, 8 бит на канал, строка dstStride байт.
    //
    // dstWidth/dstHeight — размер БУФЕРА, а не файла. Premiere при пониженном
    // качестве воспроизведения просит уменьшенный кадр, и писать туда полное
    // разрешение — выход за пределы буфера. Кадр масштабируется под запрос.
    //
    // Отрицательный dstStride переворачивает кадр по вертикали — так его ждёт
    // Premiere, у которого у 32-битных буферов начало координат внизу слева.
    // Возвращает false, если кадр получить не удалось.
    // dstStride в байтах и может быть отрицательным: у Premiere буферы идут
    // снизу вверх. Формат по умолчанию восьмибитный — тот путь, которым идёт
    // подавляющее большинство файлов, и он не должен ничего платить за наличие
    // второго.
    bool GetFrameBGRA(int64_t frameIndex, uint8_t* dst, int dstStride,
                      int dstWidth, int dstHeight,
                      FrameFormat format = FrameFormat::BGRA8);

    // Можно ли отдать этот файл вообще без пересчёта цвета.
    //
    // Замер говорит, что пересчёт в BGRA — три четверти всей работы (3.02 мс
    // из 4 на 1440p), а Premiere умеет принимать YUV 4:2:0 напрямую. Тогда
    // остаётся копирование, а перевод в RGB делает хост — и, скорее всего,
    // на видеокарте, где он почти бесплатен.
    //
    // Отказываем там, где родного формата у хоста нет: 10 бит (у него для них
    // только двухплоскостные варианты), прозрачность (в YUV её негде хранить)
    // и BT.2020 в восьми битах (такой константы у Premiere просто нет).
    bool CanDeliverYUV420() const;

    // Отдать кадр тремя плоскостями, как он лежит в файле.
    //
    // Шаги могут быть отрицательными: снизу вверх у хоста буфер или сверху
    // вниз, решает он сам и сообщает знаком — в отличие от BGRA, где переворот
    // всегда наш. Размеры плоскостей цветности вдвое меньше по обеим сторонам.
    //
    // Возвращает false, если кадр получить не удалось. Проверять
    // CanDeliverYUV420 заранее — дело вызывающего.
    bool GetFrameYUV420(int64_t frameIndex,
                        uint8_t* dstY, int strideY,
                        uint8_t* dstU, int strideU,
                        uint8_t* dstV, int strideV,
                        int dstWidth, int dstHeight);

    // Момент исходника, которому соответствует последний выданный кадр,
    // в секундах от начала клипа. Кадр источника и кадр таймлайна — не одно
    // и то же: при плавающей частоте на один кадр источника приходится
    // несколько кадров таймлайна. Нужно проверкам, чтобы измерять
    // расхождение, а не верить, что оно равно нулю.
    double LastFrameTimeSec() const { return lastFrameTimeSec_; }

    // Распаковать кадр заранее и оставить его в своём кэше.
    //
    // Нужна асинхронной выдаче: SDK разрешает планировать заранее ровно ту
    // работу, которая не зависит от размера и формата вывода, — то есть саму
    // распаковку, но не пересчёт цвета. Поэтому здесь нет ни буфера, ни
    // формата: кадр просто оказывается готовым, а GetFrameBGRA потом заберёт
    // его из кэша, не распаковывая заново.
    bool PrefetchFrame(int64_t frameIndex);

    // Ограничить кэш кадров сверху, в кадрах.
    //
    // По умолчанию бюджет считается от разрешения и целится примерно в секунду
    // видео. Асинхронному импортёру столько не нужно: он держит наготове
    // единицы кадров, а декодер у него СВОЙ — то есть без ограничения каждый
    // клип занимал бы вдвое больше памяти без всякой пользы.
    // Вызывать после Open.
    void LimitCacheToFrames(int frames);

    // Открыть дорожку звука по её номеру среди звуковых (0 — первая).
    // Отдельно от видео: у звука свой разбор контейнера, иначе перемотка
    // видео сбивала бы позицию звука и наоборот.
    bool OpenAudio(int ordinal);
    bool HasAudio() const { return audioCodec_ != nullptr; }

    // Какая дорожка открыта сейчас, или -1.
    //
    // Нужен вызывающему, чтобы отличить «звук уже открыт» от «открыт ТОТ САМЫЙ
    // звук». Без этого проверка «HasAudio?» пропускала запрос на другую дорожку
    // и молча отдавала прежнюю: у файла с четырьмя одинаковыми дорожками OBS
    // это незаметно, а на записи, где дорожки разной длины или разной
    // разрядности, Premiere получал бы чужие сведения.
    int OpenAudioTrack() const { return audioOrdinal_; }

    // Выдать отсчёты в буферы вызывающего: dst[канал][отсчёт], 32-битные float.
    // Именно в таком виде их ждёт Premiere.
    bool GetAudio(int64_t startSample, int32_t sampleCount, float* const* dst);

    // Где на самом деле уходит время. Нужно, чтобы оптимизировать по замерам,
    // а не по догадкам: декодирует видеокарта, и узким местом оказывается
    // не она, а перенос кадра в обычную память и пересчёт цвета.
    struct Stats {
        double  decodeMs   = 0.0;   // разбор и декодирование
        double  transferMs = 0.0;   // перенос из памяти видеокарты
        double  convertMs  = 0.0;   // пересчёт в BGRA
        int64_t frames     = 0;
    };
    const Stats& GetStats() const { return stats_; }
    void ResetStats() { stats_ = Stats(); }

    // Текст последней ошибки — для журнала плагина
    const std::string& LastError() const { return lastError_; }

private:
    bool OpenCodec(bool preferHardware);
    bool DecodeMoreAudio();

    // Варианты без захвата замка — для вызова изнутри, когда он уже взят
    void CloseLocked();
    void CloseAudioLocked();
    bool DecodeUntil(int64_t targetFrame);
    double FrameTimeSec(const AVFrame* f) const;

    // Метка времени исходника, в которую попадает кадр таймлайна с этим номером
    int64_t TargetTicks(int64_t timelineFrame) const;
    // Номер кадра таймлайна, с которого начинает показываться кадр с этой меткой
    int64_t TimelineIndexOf(int64_t ts) const;
    bool ConvertToBGRA(AVFrame* src, uint8_t* dst, int dstStride, int dstW, int dstH,
                       FrameFormat format);

    // Кадр под нужным номером: из кэша или распаковкой. Общая половина обоих
    // способов выдачи — без неё они разошлись бы, а расходятся такие двойники
    // молча и в сторону редких случаев (конец файла, плавающая частота).
    // Возвращает nullptr, если кадра нет; замок должен быть уже взят.
    AVFrame* AcquireFrameLocked(int64_t frameIndex);

    bool CopyToYUV420(AVFrame* src,
                      uint8_t* dstY, int strideY,
                      uint8_t* dstU, int strideU,
                      uint8_t* dstV, int strideV,
                      int dstW, int dstH);
    void ApplyColourspace(const AVFrame* src);
    void StoreInCache(int64_t index, AVFrame* src);
    void ClearCache();
    void SetError(const std::string& msg, int averr = 0);

    AVFormatContext* fmt_        = nullptr;
    AVCodecContext*  codec_      = nullptr;
    AVFrame*         frame_      = nullptr;  // кадр из декодера (может быть в памяти видеокарты)
    AVFrame*         swFrame_    = nullptr;  // копия в обычной памяти, если декодировала видеокарта

    // Текущий выбранный кадр: последний, чья метка не позже запрошенного
    // момента. Он же выручает в конце файла — avcodec_receive_frame очищает
    // кадр ещё до того, как вернёт AVERROR_EOF, и отдавать было бы нечего.
    AVFrame*         lastFrame_  = nullptr;
    bool             curValid_   = false;
    int64_t          curTs_      = 0;

    // Кадр, заглянувший за цель. Понять, что текущий кадр — нужный, можно
    // только увидев следующий: длительность кадра в контейнере не помощник,
    // Matroska проставляет её из заголовка и на плавающей частоте врёт.
    // Выброшенным он был бы декодирован заново на следующем же запросе.
    AVFrame*         aheadFrame_ = nullptr;
    bool             aheadValid_ = false;
    int64_t          aheadTs_    = 0;

    // Допуск на округление меток в контейнере: Matroska хранит их в
    // миллисекундах, и метка кадра 60 fps оказывается на доли миллисекунды
    // раньше расчётной. Четверть кадра — заведомо больше этой погрешности
    // и заведомо меньше настоящего интервала между кадрами.
    int64_t          toleranceTicks_ = 0;
    AVPacket*        packet_     = nullptr;
    SwsContext*      sws_        = nullptr;
    int              swsSrcW_    = 0;   // с какими параметрами создан пересчётчик
    int              swsSrcH_    = 0;
    int              swsSrcFmt_  = -1;
    int              swsDstW_    = 0;
    int              swsDstH_    = 0;
    int              swsDstFmt_  = -1;  // пересчётчик кэшируется и по формату выхода

    // Отдельный пересчётчик для выдачи плоскостями. Отдельный, потому что
    // формат выхода у него другой, а тот, что выше, сам себя пересоздаёт при
    // смене формата — держи мы один на оба пути, он пересоздавался бы на
    // каждом кадре. Нужен не всегда: при совпадении размеров и формата кадр
    // копируется построчно, минуя swscale вовсе.
    SwsContext*      swsYuv_     = nullptr;

    // Цветовое описание из контейнера. Нужно потому, что в самом потоке его
    // может не быть: SVT-AV1, например, не пишет его в заголовок
    // последовательности, и кадр приезжает с «не указано».
    int              streamColourspace_ = 2;   // AVCOL_SPC_UNSPECIFIED
    int              streamColourRange_ = 0;   // AVCOL_RANGE_UNSPECIFIED
    AVBufferRef*     hwDevice_   = nullptr;

    int      videoStream_ = -1;
    int      codecId_     = 0;   // AVCodecID открытого потока; таблица — в .cpp
    MediaInfo info_;
    std::string lastError_;

    // Кэш позиции: Premiere почти всегда читает кадры подряд, и без этого
    // на каждый кадр приходилось бы перематывать файл с начала.
    int64_t  lastDecodedFrame_ = -1;
    bool     eofReached_       = false;
    double   lastFrameTimeSec_ = 0.0;

    // Общий ноль клипа: момент, от которого считаются и кадры, и отсчёты
    // звука. Ноль у большинства файлов, но не у всех — см. Open().
    double   startTimeSec_     = 0.0;

    // Кэш кадров. Заполняется только при отматывании назад: там мы всё равно
    // декодируем весь отрезок от опорного кадра, и без кэша выбрасывали бы
    // ровно те кадры, которые попросят следующим шагом.
    std::map<int64_t, AVFrame*> frameCache_;
    size_t   cacheBytes_    = 0;
    size_t   cacheBudget_   = 0;    // сколько хочет ЭТОТ клип, см. Open()

    // Сколько памяти ему достанется с учётом остальных клипов, см. Budget()
    size_t   Budget() const;

    // Сколько декодеров видео живо в процессе. Общий предел делится между ними,
    // иначе каждый клип на таймлайне заводит свой кэш и общая цифра ничем
    // не ограничена: на 1440p это 331 МБ на клип.
    //
    // Статический счётчик, а не поле — декодеры друг о друге не знают и знать
    // не должны, а число их нужно каждому.
    static std::atomic<int> videoDecoders_;

    // Сколько потоков дать декодеру, который открывается сейчас: число ядер
    // делится между живыми. Обоснование и замеры — в .cpp
    static int ThreadsForNewDecoder();

    bool     countedAsVideo_ = false;   // учтён ли ЭТОТ в счётчике
    bool     cacheFill_     = false;
    int64_t  lastRequested_ = -1;

    // --- звук ---
    AVFormatContext* audioFmt_   = nullptr;  // свой разбор контейнера, см. OpenAudio
    AVCodecContext*  audioCodec_ = nullptr;
    AVFrame*         audioFrame_ = nullptr;
    AVPacket*        audioPacket_ = nullptr;
    SwrContext*      swr_        = nullptr;
    int              audioStreamIndex_ = -1;
    int              audioOrdinal_     = -1;  // номер СРЕДИ ЗВУКОВЫХ, как его просили

    // Готовые отсчёты, оставшиеся от предыдущего запроса: Premiere просит
    // произвольные куски, а декодер выдаёт кадрами по ~1024 отсчёта
    std::vector<std::vector<float>> pending_;
    int64_t pendingOffset_ = 0;
    int64_t pendingCount_  = 0;
    int64_t audioCursor_   = -1;   // номер следующего готового отсчёта

    // Замки раздельные, и это важно. Видео и звук разбираются полностью
    // независимо (у каждого свой контекст контейнера), а Premiere читает их
    // одновременно: кадры для показа и звук для конформирования. Один общий
    // замок ставил бы звук в очередь за непрерывным потоком кадров.
    // Порядок захвата, когда нужны оба: сначала видео, потом звук.
    Stats stats_;

    std::mutex mutex_;
    std::mutex audioMutex_;
};

} // namespace av1imp
