// Асинхронная выдача кадров.
//
// Обычным путём Premiere просит кадр и ждёт, пока мы его распакуем. Здесь он
// может заказать кадры вперёд и забрать их позже: распаковка идёт, пока хост
// занят своим. Ради этого Adobe и завёл отдельную точку входа.
//
// Главное правило из SDK, и оно не формальность: **асинхронный импортёр не
// имеет права ссылаться на обычный** — их время жизни развязано, обычный может
// быть закрыт раньше. Поэтому здесь свой декодер, своя копия пути к файлу и
// свои указатели на наборы функций хоста, а не ссылка на чужую структуру.

#pragma once

#include "AV1Importer.h"

namespace av1imp {

// Создать асинхронный импортёр по данным уже открытого обычного.
// Возвращает false, если создать не удалось: тогда хост продолжит пользоваться
// обычным путём, и ничего страшного не произойдёт.
bool CreateAsyncImporter(ImporterLocalRecPtr source, imAsyncImporterCreationRec* rec);

// Включена ли асинхронная выдача. Читается из того же файла настроек, что и
// выбор декодера: путь новый и с потоками, и выключатель тут не роскошь.
bool AsyncEnabled();

} // namespace av1imp
