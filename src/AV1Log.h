// Журнал плагина.
//
// Внутри Premiere отладчик подключать неудобно, а любой отказ импортёра выглядит
// одинаково: "unsupported compression type". Журнал отвечает на главный вопрос —
// спросил ли Premiere наш плагин вообще, и если да, на чём тот споткнулся.
//
// Файл: %LOCALAPPDATA%\Aether\log.txt, перезаписывается при каждой загрузке
// плагина, поэтому не растёт бесконечно и всегда относится к текущему запуску.

#pragma once

#include <string>

namespace av1imp {

void LogReset();                          // вызывается один раз при загрузке плагина
void LogClose();                          // при выгрузке плагина
void Log(const char* format, ...);        // строка в журнал

// Широкую строку — в UTF-8, для передачи в Log через обычный %s.
//
// Печатать её через %S НЕЛЬЗЯ, и это не придирка, а измерено. MSVC переводит
// %S по текущей локали C, а она по умолчанию «C», то есть только ASCII: на
// первом же символе вне латиницы fprintf останавливается, возвращает -1 и
// НЕ ПИШЕТ ДАЖЕ ПЕРЕВОД СТРОКИ — следующая запись приклеивается к обрубку.
//
//     1 ascii  [C:\Users\hadeg\file.mp4] end     <- 39 символов, всё хорошо
//     2 cyrill [F:\                              <- обрыв, -1, без \n
//
// Путь к файлу — ровно то, ради чего журнал открывают, когда файл не взялся.
// У всякого, кто держит материал не в латинских папках, эта строка была
// обрублена именно тогда, когда была нужна.
std::string Utf8(const wchar_t* wide);

// Путь к файлу для журнала: в UTF-8 и без домашней папки.
//
// Компромисс между двумя правильными желаниями, и оба надо было учесть.
//
// С одной стороны, журнал прикладывают к публичным issue, а домашняя папка
// несёт имя пользователя, иногда с фамилией. С другой — «какой это был файл»
// это САМАЯ полезная строка, когда файл не импортируется: по ней видно и
// приставку \\?\, и путь по сети, и необычные символы, и обрезание. Заменить
// её непрозрачным идентификатором значит выбросить ровно то, ради чего
// журнал и открывают.
//
// Поэтому ни того, ни другого: путь остаётся целиком, а домашняя папка
// становится %USERPROFILE%. Приём не новый — так же поступает Scrub
// в диагностическом отчёте, и незачем иметь на это два разных правила.
std::string LogPath(const wchar_t* path);

// Имя запроса Premiere по его номеру — читать журнал по цифрам невыносимо
const char* SelectorName(int selector);

} // namespace av1imp
